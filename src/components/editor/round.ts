/**
 * 毫米取整的**唯一一份**实现（0.1mm 粒度）。
 *
 * ## 为什么会有这个文件
 *
 * 收口前，同一个 `round1` 在项目里存在 **5 份**副本：
 *   `template-store.ts:73` / `table-actions.ts` / `EditorShell.tsx:104` /
 *   `Canvas.tsx:70` / `Inspector.tsx:1872`。
 *
 * 而且它们**不是同一种行为**：其中 4 份是 `Math.round(n * 10) / 10`，
 * 只有 `Inspector.tsx` 那一份是 `Math.round(finite(n, 0) * 10) / 10`。
 * 两者只在**非有限输入**上分叉（见下），在全部有限输入上逐字节相同 ——
 * 也就是说，按"多数派"（4/5）机械收口，会**静默删掉**那唯一的守卫，
 * 而任何行为断言都不会因此变红。
 *
 * 所以这里统一到**带守卫**的那一份，理由三条：
 *
 * 1. 有限输入上两者完全一致 → 对其余 4 处调用点是零行为变化；
 * 2. 丢守卫是**数据损坏方向**的：`NaN` 会一路流进 patch、落到合并后的 doc 里，
 *    而保守卫只是把非法输入钳到 0；
 * 3. 让"唯一多出来的行为"落在**安全**的那一侧。
 *
 * ## ⚠️ 别把守卫当多余的防御删掉
 *
 * `NaN` / `±Infinity` / `undefined` 在业务上确实"不该出现"，但**它们到得了这里**：
 * 例如 `pageRenderSize()` 对 `paper === 'custom'` 是直接读 `pageSetup.widthMm`
 * 而不做校验。守卫不是防御性编程洁癖，是这个函数目前唯一在边界上正确的行为。
 *
 * **注意：这不是一次纯重构。** 其余 4 处此前没有守卫，
 * 统一到本实现后它们在非有限输入上的行为从 `NaN`/`Infinity` 变成 `0` —— 是有意的行为变化。
 *
 * ## 依赖
 *
 * 只有 `../../lib/types`（`finite` 已经是那一处的单一导出）。
 * 与 `table-query.ts` 同性质：纯、无 DOM、可被 Node 直接加载。
 */

import { finite } from '../../lib/types'

/**
 * 取到 0.1mm。
 *
 * 非有限输入（`NaN` / `±Infinity` / `undefined`）一律钳到 `0`，而不是把 `NaN` 传下去。
 *
 * 已知的浮点表现，**不要"顺手修"**：
 *   `round1(1.005) === 1`（不是 1.01）—— 因为 `1.005 * 10 === 10.049999999999999`。
 *   这是 `Math.round` 的正常行为，改它会产生真实的差异（`__selftest.mts` 把它钉住了）。
 */
export function round1(n: number): number {
  return Math.round(finite(n, 0) * 10) / 10
}
